const ChannelMark = ({ channel }: { channel: ChannelLogo }) => {
  const [failed, setFailed] = useState(false);
  const showImage = Boolean(channel.src) && !failed;

  if (!showImage) return <>{channel.mark}</>;

  return (
    <img
      src={channel.src}
      alt=""
      className={`h-full w-auto max-h-full object-contain ${
        channel.invert === false ? '' : 'brightness-0 invert'
      }`}
      loading="lazy"
      decoding="async"
      referrerPolicy="no-referrer"
      onError={() => setFailed(true)}
    />
  );
};

type ChannelLogoMarqueeProps = {
  compact?: boolean;
  items?: ChannelLogo[];
};

const ChannelLogoMarquee = ({
  compact = false,
  items = channelLogos,
}: ChannelLogoMarqueeProps) => {
  const row = (copy: 'a' | 'b') => (
    <ul className={`flex m-0 list-none items-center p-0 ${GAP}`} aria-hidden={copy === 'b' || undefined}>
      {items.map(channel => (
        <li
          key={`${copy}-${channel.name}`}
          className={`flex shrink-0 items-center justify-center text-white ${
            compact ? 'h-8' : 'h-10'
          }`}
        >
          <ChannelMark channel={channel} />
          <span className="sr-only">{channel.name}</span>
        </li>
      ))}
    </ul>
  );

  return (
    <div className="channel-marquee relative overflow-hidden">
      <div className={`channel-marquee-track flex w-max items-center ${GAP}`}>
        {row('a')}
        {row('b')}
      </div>
    </div>
  );
};

